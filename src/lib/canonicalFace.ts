function cPt(idx: number): [number, number] {
  return [CANONICAL_FACE_XYZ[idx * 3]!, CANONICAL_FACE_XYZ[idx * 3 + 1]!];
}

function midPt(a: [number, number], b: [number, number]): [number, number] {
  return [(a[0] + b[0]) * 0.5, (a[1] + b[1]) * 0.5];
}

export function fitCanonicalLandmarks(
  kp: FaceKeypoints,
  aspect: number,
): Array<[number, number, number]> {
  const cRightEye = midPt(cPt(33), cPt(133));
  const cLeftEye = midPt(cPt(362), cPt(263));
  const cEyeMid = midPt(cRightEye, cLeftEye);
  const cMouthCenter = midPt(cPt(13), cPt(14));
  const cEyeVecX = cLeftEye[0] - cRightEye[0];
  const cEyeVecY = cLeftEye[1] - cRightEye[1];
  const cEyeDist = Math.hypot(cEyeVecX, cEyeVecY) || 6.3;
  const cEyeToMouth = cMouthCenter[1] - cEyeMid[1];

  const tRightEye: [number, number] = [kp.rightEye[0] * aspect, kp.rightEye[1]];
  const tLeftEye: [number, number] = [kp.leftEye[0] * aspect, kp.leftEye[1]];
  const tEyeMid = midPt(tRightEye, tLeftEye);
  const tMouthCenter: [number, number] = [kp.mouthCenter[0] * aspect, kp.mouthCenter[1]];

  const dx = tLeftEye[0] - tRightEye[0];
  const dy = tLeftEye[1] - tRightEye[1];
  const tEyeDist = Math.max(0.04, Math.hypot(dx, dy));
  const ux = dx / tEyeDist;
  const uy = dy / tEyeDist;
  let vx = -uy;
  let vy = ux;
  if (vy < 0) {
    vx = -vx;
    vy = -vy;
  }

  const scaleX = tEyeDist / cEyeDist;
  const projMouthV = (tMouthCenter[0] - tEyeMid[0]) * vx + (tMouthCenter[1] - tEyeMid[1]) * vy;
  const rawScaleY = projMouthV > 0.02 ? projMouthV / cEyeToMouth : scaleX;
  const scaleY = Math.min(scaleX * 1.45, Math.max(scaleX * 0.65, rawScaleY));

  const projectBase = (cx: number, cy: number): [number, number] => {
    const lx = (cx - cEyeMid[0]) * scaleX;
    const ly = (cy - cEyeMid[1]) * scaleY;
    return [tEyeMid[0] + ux * lx + vx * ly, tEyeMid[1] + uy * lx + vy * ly];
  };

  const tNoseTip: [number, number] = [kp.noseTip[0] * aspect, kp.noseTip[1]];
  const dNoseRight = Math.max(0.01, tNoseTip[0] - tRightEye[0]);
  const dNoseLeft = Math.max(0.01, tLeftEye[0] - tNoseTip[0]);
  const yawBias = Math.max(-0.55, Math.min(0.55, (dNoseRight - dNoseLeft) / tEyeDist));

  const anchors: Array<{ idx: number; target: [number, number]; radius: number; weight: number }> =
    [
      {
        idx: 1,
        target: tNoseTip,
        radius: tEyeDist * 0.55,
        weight: 0.9,
      },
      { idx: 13, target: tMouthCenter, radius: tEyeDist * 0.65, weight: 0.9 },
    ];
  if (kp.mouthLeft) {
    anchors.push({
      idx: 61,
      target: [kp.mouthLeft[0] * aspect, kp.mouthLeft[1]],
      radius: tEyeDist * 0.45,
      weight: 0.95,
    });
  }
  if (kp.mouthRight) {
    anchors.push({
      idx: 291,
      target: [kp.mouthRight[0] * aspect, kp.mouthRight[1]],
      radius: tEyeDist * 0.45,
      weight: 0.95,
    });
  }
  if (kp.chin) {
    anchors.push({
      idx: 152,
      target: [kp.chin[0] * aspect, kp.chin[1]],
      radius: tEyeDist * 0.8,
      weight: 0.85,
    });
  }
  if (kp.forehead) {
    anchors.push({
      idx: 10,
      target: [kp.forehead[0] * aspect, kp.forehead[1]],
      radius: tEyeDist * 0.85,
      weight: 0.8,
    });
  }
  if (kp.rightCheek) {
    anchors.push({
      idx: 234,
      target: [kp.rightCheek[0] * aspect, kp.rightCheek[1]],
      radius: tEyeDist * 0.75,
      weight: 0.75,
    });
  } else if (Math.abs(yawBias) > 0.14) {
    // Contract far cheek edge gently on 3/4 views when explicit cheek wasn't supplied
    const [bx, by] = projectBase(cPt(234)[0], cPt(234)[1]);
    anchors.push({
      idx: 234,
      target: [bx + (tEyeMid[0] - bx) * Math.max(0, -yawBias * 0.42), by],
      radius: tEyeDist * 0.75,
      weight: 0.55,
    });
  }
  if (kp.leftCheek) {
    anchors.push({
      idx: 454,
      target: [kp.leftCheek[0] * aspect, kp.leftCheek[1]],
      radius: tEyeDist * 0.75,
      weight: 0.75,
    });
  } else if (Math.abs(yawBias) > 0.14) {
    const [bx, by] = projectBase(cPt(454)[0], cPt(454)[1]);
    anchors.push({
      idx: 454,
      target: [bx + (tEyeMid[0] - bx) * Math.max(0, yawBias * 0.42), by],
      radius: tEyeDist * 0.75,
      weight: 0.55,
    });
  }

  const anchorDeltas = anchors.map((a) => {
    const [cx, cy] = cPt(a.idx);
    const [bx, by] = projectBase(cx, cy);
    return {
      bx,
      by,
      dx: (a.target[0] - bx) * a.weight,
      dy: (a.target[1] - by) * a.weight,
      invR2: 1 / Math.max(1e-4, a.radius * a.radius),
    };
  });

  const out: Array<[number, number, number]> = new Array(468);
  for (let i = 0; i < 468; i++) {
    const cx = CANONICAL_FACE_XYZ[i * 3]!;
    let cy = CANONICAL_FACE_XYZ[i * 3 + 1]!;
    const cz = CANONICAL_FACE_XYZ[i * 3 + 2]!;

    if (kp.stylized) {
      if (RIGHT_EYE_VERTS.has(i)) {
        cy = cRightEye[1] + (cy - cRightEye[1]) * 1.48;
      } else if (LEFT_EYE_VERTS.has(i)) {
        cy = cLeftEye[1] + (cy - cLeftEye[1]) * 1.48;
      }
    }

    const [bx, by] = projectBase(cx, cy);
    let sx = 0;
    let sy = 0;
    let wSum = 0;
    for (const ad of anchorDeltas) {
      const d2 = (bx - ad.bx) * (bx - ad.bx) + (by - ad.by) * (by - ad.by);
      const w = Math.exp(-d2 * ad.invR2);
      sx += ad.dx * w;
      sy += ad.dy * w;
      wSum += w;
    }
    const norm = wSum > 1 ? 1 / wSum : 1;
    const fx = (bx + sx * norm) / aspect;
    const fy = by + sy * norm;
    const fz = -((cz - 2.5) / 10) * scaleX * 0.85;
    out[i] = [fx, fy, fz];
  }
  return out;
}
